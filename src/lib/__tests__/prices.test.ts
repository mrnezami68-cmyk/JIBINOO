/* تست‌های اجرایی — موتور قیمت (فاز ۱۴): لایه محافظ واحد ریال/تومان */
import { describe, expect, it } from 'vitest';
import { fixUnit } from '../prices';

describe('fixUnit — تطبیق خودکار واحد ریال/تومان (باگ طلای ۱۸/۲۴ عیار)', () => {
  it('مقدار ریالی ۱۰ برابر → به تومان تبدیل می‌شود (گزارش کاربر: طلای ۱۸)', () => {
    // فید: ۲۴۱٬۲۴۶٬۰۰۰ (ریال) — مقدار درست: ۲۴٬۱۲۴٬۶۰۰ تومان
    expect(fixUnit(241_246_000, 24_124_600)).toBe(24_124_600);
  });

  it('مقدار تومانی درست → دست‌نخورده می‌ماند', () => {
    expect(fixUnit(24_124_600, 24_124_600)).toBe(24_124_600);
  });

  it('نوسان عادی بازار (تا ۵ برابر) هرگز تصحیح نمی‌شود', () => {
    expect(fixUnit(24_124_600 * 2, 24_124_600)).toBe(24_124_600 * 2);
    expect(fixUnit(24_124_600 * 4.9, 24_124_600)).toBeCloseTo(24_124_600 * 4.9, 5);
    expect(fixUnit(24_124_600 / 3, 24_124_600)).toBe(24_124_600 / 3);
  });

  it('مقدار ۱۰ برابر کوچک‌تر → ضرب در ۱۰ (اگر فید روزی تومانی شود)', () => {
    expect(fixUnit(2_412_460, 24_124_600)).toBe(24_124_600);
  });

  it('بدون مرجع معتبر (صفر/NaN) مقدار خام برمی‌گردد', () => {
    expect(fixUnit(241_246_000, 0)).toBe(241_246_000);
    expect(fixUnit(241_246_000, NaN)).toBe(241_246_000);
    expect(fixUnit(NaN, 24_124_600)).toBe(NaN);
    expect(fixUnit(-5, 100)).toBe(-5);
  });
});
